// The frame every generated pgTAP file shares: the GENERATED header, BEGIN, plan, the psql files it pulls in,
// finish and ROLLBACK, and writing it. Each generator (scripts/*-sql.ts) renders only its own cases.

import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

export type CaseSqlFile = {
	// The package script that writes the file, e.g. "gen:ledger-cases".
	script: string;
	// The table it is rendered from, and the bun test that fails while it is stale.
	table: string;
	driftTest: string;
	// What the file checks, in sentences.
	about: string;
	tests: number;
	// Files in supabase/tests/ pulled in after plan().
	includes?: string[];
	body: string;
};

const RULE = "-- ============================================================================";
const WIDTH = 120;

export function sqlTestPath(fileName: string): string {
	return join(import.meta.dir, "..", "supabase", "tests", fileName);
}

export function sqlString(value: string): string {
	return `'${value.replaceAll("'", "''")}'`;
}

function comment(text: string): string[] {
	const lines: string[] = [];
	let line = "--";
	for (const word of text.split(" ")) {
		if (line.length + 1 + word.length > WIDTH && line !== "--") {
			lines.push(line);
			line = "--";
		}
		line += ` ${word}`;
	}
	return [...lines, line];
}

export function renderCaseSqlFile(file: CaseSqlFile): string {
	const generated =
		`GENERATED by \`bun run ${file.script}\` from ${file.table}. Don't edit it by hand: change the table and ` +
		`regenerate (${file.driftTest} fails while it is stale). ${file.about} Everything is rolled back.`;
	return [
		RULE,
		...comment(generated),
		RULE,
		"BEGIN;",
		"CREATE EXTENSION IF NOT EXISTS pgtap WITH SCHEMA extensions;",
		`SELECT plan(${file.tests});`,
		...(file.includes ?? []).map((name) => String.raw`\ir ${name}`),
		"",
		file.body,
		"",
		"SELECT * FROM finish();",
		"ROLLBACK;",
		"",
	].join("\n");
}

// A file in supabase/tests/ as text, whatever line endings it was checked out with.
export function readSqlFile(path: string): string {
	return readFileSync(path, "utf8").replaceAll("\r\n", "\n");
}

export function writeCaseSqlFile(path: string, text: string, summary: string): void {
	writeFileSync(path, text);
	console.log(`Wrote ${summary} to ${path}`);
}
