// Renders the shared case table (tests/fixtures/ledger-cases.ts) into a pgTAP file that runs every case
// through private.compute_shares. It only formats: the expected cents are the table's, never computed.
// `bun run gen:ledger-cases` writes the file; tests/lib/ledger-cases-sql.test.ts checks it is current.

import { writeFileSync } from "node:fs";
import { join } from "node:path";

import { LEDGER_CASES } from "../tests/fixtures/ledger-cases";
import type { LedgerCase } from "../tests/fixtures/ledger-cases";

export const LEDGER_CASES_SQL_PATH = join(import.meta.dir, "..", "supabase", "tests", "ledger_cases.test.sql");

// The n-th person in a case's `members` gets the same id in every case.
export function memberUuid(index: number): string {
	return `00000000-0000-4000-8000-${String(index + 1).padStart(12, "0")}`;
}

function sqlString(value: string): string {
	return `'${value.replaceAll("'", "''")}'`;
}

function renderCase(ledgerCase: LedgerCase): string {
	const idOf = (name: string) => {
		const index = ledgerCase.members.indexOf(name);
		if (index < 0) throw new Error(`${ledgerCase.name}: ${name} is not in members`);
		return memberUuid(index);
	};

	const shareNames = Object.keys(ledgerCase.owed);
	const paidNames = Object.keys(ledgerCase.paid);
	if (paidNames.length !== shareNames.length || paidNames.some((name) => !(name in ledgerCase.owed))) {
		throw new Error(`${ledgerCase.name}: paid and owed must name the same people`);
	}

	const items = JSON.stringify(
		ledgerCase.items.map((item) => ({
			amountCents: item.amountCents,
			paidBy: idOf(item.paidBy),
			splitAmong: item.splitAmong.map(idOf),
		}))
	);
	const rows = shareNames.map((name, index) => {
		const comma = index < shareNames.length - 1 ? "," : "";
		return `        (${sqlString(idOf(name))}::UUID, ${ledgerCase.paid[name]}::BIGINT, ${ledgerCase.owed[name]}::BIGINT)${comma} -- ${name}`;
	});

	return [
		`-- ${ledgerCase.name}`,
		"SELECT results_eq(",
		`    $$ SELECT member_id, paid_cents, owed_cents FROM private.compute_shares(${sqlString(items)}::JSONB) $$,`,
		"    $$ VALUES",
		...rows,
		"    $$,",
		`    ${sqlString(ledgerCase.name)}`,
		");",
	].join("\n");
}

export function renderLedgerCasesSql(cases: LedgerCase[]): string {
	return [
		"-- ============================================================================",
		"-- GENERATED by `bun run gen:ledger-cases` from tests/fixtures/ledger-cases.ts. Don't edit it by hand:",
		"-- change the case table and regenerate (tests/lib/ledger-cases-sql.test.ts fails while it is stale).",
		"-- Every pinned bill runs through private.compute_shares, the SQL twin of computeShares in",
		"-- src/lib/ledger.ts, and must return the hand-worked shares in bill order.",
		"-- ============================================================================",
		"BEGIN;",
		"CREATE EXTENSION IF NOT EXISTS pgtap WITH SCHEMA extensions;",
		`SELECT plan(${cases.length});`,
		"",
		cases.map(renderCase).join("\n\n"),
		"",
		"SELECT * FROM finish();",
		"ROLLBACK;",
		"",
	].join("\n");
}

if (import.meta.main) {
	writeFileSync(LEDGER_CASES_SQL_PATH, renderLedgerCasesSql(LEDGER_CASES));
	console.log(`Wrote ${LEDGER_CASES.length} cases to ${LEDGER_CASES_SQL_PATH}`);
}
