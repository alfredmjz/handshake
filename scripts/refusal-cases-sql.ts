// Renders the refusal case table (tests/fixtures/refusal-cases.ts) into a pgTAP file that pushes each case's
// mutation through push_changes() as its actor, from the world in supabase/tests/refusal-world.psql, and checks
// the outcome. It only formats: the expected codes are the table's.
// `bun run gen:refusal-cases` writes the file; tests/lib/refusal-cases-sql.test.ts checks it is current.

import { writeFileSync } from "node:fs";
import { join } from "node:path";

import { expectedOutcome, GROUP, REFUSAL_CASES, USERS } from "../tests/fixtures/refusal-cases";
import type { GroupSetup, RefusalCase } from "../tests/fixtures/refusal-cases";

export const REFUSAL_CASES_SQL_PATH = join(import.meta.dir, "..", "supabase", "tests", "refusal_cases.test.sql");

function sqlString(value: string): string {
	return `'${value.replaceAll("'", "''")}'`;
}

// What the owner pushes first to get the group into the case's state.
const SETUP: Record<GroupSetup, string> = {
	open: "NULL",
	completed: sqlString(JSON.stringify({ type: "group.complete", groupId: GROUP })),
	deleted: sqlString(JSON.stringify({ type: "group.delete", groupId: GROUP })),
};

function renderCase(refusalCase: RefusalCase): string {
	const expected = expectedOutcome(refusalCase, "pushChanges");
	const description = refusalCase.mismatch
		? `${refusalCase.name} (known mismatch: ${refusalCase.mismatch.why})`
		: refusalCase.name;
	const outcome = `pg_temp.outcome(${SETUP[refusalCase.group]}, ${sqlString(USERS[refusalCase.actor])}, ${sqlString(JSON.stringify(refusalCase.mutation))})`;
	return [
		`-- ${refusalCase.mutation.type}`,
		`SELECT is(${outcome}, ${sqlString(expected === "accepted" ? "applied" : expected)}, ${sqlString(description)});`,
	].join("\n");
}

export function renderRefusalCasesSql(cases: RefusalCase[]): string {
	return [
		"-- ============================================================================",
		"-- GENERATED by `bun run gen:refusal-cases` from tests/fixtures/refusal-cases.ts. Don't edit it by hand:",
		"-- change the case table and regenerate (tests/lib/refusal-cases-sql.test.ts fails while it is stale).",
		"-- Each case pushes one mutation as its actor from the world in refusal-world.psql and checks it is applied",
		"-- or refused with the table's code; planChange is held to the same table (tests/lib/refusal-cases.test.ts).",
		"-- Everything is rolled back.",
		"-- ============================================================================",
		"BEGIN;",
		"CREATE EXTENSION IF NOT EXISTS pgtap WITH SCHEMA extensions;",
		`SELECT plan(${cases.length});`,
		String.raw`\ir prelude.psql`,
		String.raw`\ir refusal-world.psql`,
		"",
		cases.map(renderCase).join("\n\n"),
		"",
		"SELECT * FROM finish();",
		"ROLLBACK;",
		"",
	].join("\n");
}

if (import.meta.main) {
	writeFileSync(REFUSAL_CASES_SQL_PATH, renderRefusalCasesSql(REFUSAL_CASES));
	console.log(`Wrote ${REFUSAL_CASES.length} cases to ${REFUSAL_CASES_SQL_PATH}`);
}
